import { createFileRoute, Link } from "@tanstack/react-router";
import { insertPlayer } from "@/lib/players";
import { rememberRoom } from "@/lib/prefs";
import { useEffect, useState, type FormEvent } from "react";
import { Shell } from "@/components/shell";
import { Button, Field, buttonBase, buttonTone, inputClass, cx, joinLink } from "@/components/ui";
import { Egg, GameIcon, Glyph, Mark, gameStyle, gameVars } from "@/components/brand";
import { QrCode } from "@/components/qr-code";
import { ensureSession, supabase } from "@/lib/supabase";
import { CATALOG, PLAYABLE_SLUGS, findCard } from "@/lib/catalog";

/**
 * Create-room page. Lists the playable games from Supabase (see lib/catalog), then creates a room for
 * the chosen game and adds the visitor as host. The room code is generated by
 * the database trigger, so it's read back from the inserted row.
 */
export const Route = createFileRoute("/play")({
  validateSearch: (search: Record<string, unknown>): { game: string; room?: string } => ({
    game: typeof search.game === "string" ? search.game : "",
    // A room the host already has (a new round after a game): open its lobby.
    ...(typeof search.room === "string" && search.room ? { room: search.room } : {}),
  }),
  head: () => ({ meta: [{ title: "إنشاء غرفة — العش" }] }),
  component: CreatePage,
});

type GameRow = {
  id: string;
  slug: string;
  title_ar: string;
  description_ar: string;
  min_players: number;
  max_players: number;
  home_status?: string | null;
  sort_order?: number | null;
};

type RoomRow = {
  id: string;
  room_code: string;
  game_id: string;
  status: string;
};

type PlayerRow = {
  id: string;
  player_name: string;
  is_host: boolean;
  avatar?: { c?: number; e?: string | null } | null;
};

function CreatePage() {
  const { game: preselected, room: roomParam } = Route.useSearch();
  const [games, setGames] = useState<GameRow[] | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);
  // The URL carries a game slug (e.g. tactical-grid). Selection uses the row id.
  const [selected, setSelected] = useState<string>("");
  const [hostName, setHostName] = useState("");
  const [busy, setBusy] = useState(false);
  const [formError, setFormError] = useState<string | null>(null);
  const [room, setRoom] = useState<RoomRow | null>(null);
  const [players, setPlayers] = useState<PlayerRow[]>([]);
  const [playersError, setPlayersError] = useState<string | null>(null);
  const [starting, setStarting] = useState(false);
  const [startError, setStartError] = useState<string | null>(null);

  // When the page opens with ?game=<slug>, select that game once the list is loaded.
  useEffect(() => {
    if (!games || !preselected) return;
    const match = games.find((g) => g.slug === preselected);
    if (match) setSelected(match.id);
  }, [games, preselected]);

  // Load the active games (public read per RLS).
  useEffect(() => {
    if (!supabase) {
      setLoadError("الاتصال بقاعدة البيانات غير مضبوط بعد.");
      return;
    }
    const client = supabase;
    const base = "id, slug, title_ar, description_ar, min_players, max_players";
    (async () => {
      // home_status and sort_order arrive with supabase/polish_v1.sql; read without them before that.
      const full = await client.from("games").select(`${base}, home_status, sort_order`).eq("is_active", true);
      const res = full.error ? await client.from("games").select(base).eq("is_active", true) : full;
      if (res.error) {
        setLoadError("تعذّر تحميل الألعاب، حاول مرة أخرى.");
        return;
      }
      // Only games the site has a room for, and that the admin offers (not «قريبًا» or hidden), in the admin's order.
      const rows = ((res.data ?? []) as GameRow[]).filter((g) => PLAYABLE_SLUGS.has(g.slug) && (g.home_status ?? "live") === "live");
      const pos = (g: GameRow) => g.sort_order ?? 1000 + CATALOG.findIndex((c) => c.id === g.slug);
      setGames(rows.sort((a, b) => pos(a) - pos(b)));
    })();
  }, []);

  // ?room=CODE: the host's existing room, back in its lobby for a new round.
  const [resuming, setResuming] = useState(!!roomParam);
  useEffect(() => {
    if (!roomParam || !supabase) {
      setResuming(false);
      return;
    }
    const client = supabase;
    let alive = true;
    (async () => {
      try {
        const session = await ensureSession();
        const { data } = await client
          .from("game_rooms")
          .select("id, room_code, game_id, status, host_id")
          .eq("room_code", roomParam.toUpperCase())
          .maybeSingle();
        if (!alive) return;
        const found = data as (RoomRow & { host_id: string }) | null;
        if (!found || found.host_id !== session.user.id) setFormError("لم نجد غرفتك. أنشئ غرفة جديدة.");
        else if (found.status !== "finished") {
          setRoom({ id: found.id, room_code: found.room_code, game_id: found.game_id, status: found.status });
          rememberRoom(found.room_code, true);
        }
      } finally {
        if (alive) setResuming(false);
      }
    })();
    return () => {
      alive = false;
    };
  }, [roomParam]);

  // Once a room exists, keep its player list live. Any insert, update or delete
  // on this room's players triggers a fresh read, which respects RLS.
  useEffect(() => {
    if (!supabase || !room) return;
    const client = supabase;
    const roomId = room.id;
    let cancelled = false;

    async function loadPlayers() {
      try {
        const { data, error } = await client
          .from("room_players")
          .select("*")
          .eq("room_id", roomId)
          .order("joined_at");
        if (cancelled) return;
        if (error) {
          // Show the real reason on screen instead of an empty list.
          setPlayersError(`تعذّر تحديث قائمة اللاعبين: ${error.message}`);
          return;
        }
        setPlayers((data ?? []) as PlayerRow[]);
        setPlayersError(null);
      } catch (err) {
        if (!cancelled) setPlayersError(`تعذّر تحديث قائمة اللاعبين: ${err instanceof Error ? err.message : String(err)}`);
      }
    }

    loadPlayers();
    const channel = client
      .channel(`room-players-${roomId}`)
      .on(
        "postgres_changes",
        { event: "*", schema: "public", table: "room_players", filter: `room_id=eq.${roomId}` },
        () => {
          loadPlayers();
        },
      )
      .subscribe();

    // Fallback: realtime can drop silently on a phone or a sleeping tab. Re-read the list every few seconds.
    const timer = window.setInterval(loadPlayers, 3000);
    const onVisible = () => {
      if (document.visibilityState === "visible") loadPlayers();
    };
    document.addEventListener("visibilitychange", onVisible);

    return () => {
      cancelled = true;
      window.clearInterval(timer);
      document.removeEventListener("visibilitychange", onVisible);
      client.removeChannel(channel);
    };
  }, [room]);

  // Keep the room status live, so the host sees changes made from anywhere.
  useEffect(() => {
    if (!supabase || !room) return;
    const client = supabase;
    const roomId = room.id;
    const channel = client
      .channel(`room-status-${roomId}`)
      .on(
        "postgres_changes",
        { event: "UPDATE", schema: "public", table: "game_rooms", filter: `id=eq.${roomId}` },
        (payload) => {
          const next = (payload.new as { status?: string }).status;
          if (next) setRoom((current) => (current ? { ...current, status: next } : current));
        },
      )
      .subscribe();

    return () => {
      client.removeChannel(channel);
    };
  }, [room?.id]);

  async function startGame() {
    if (!supabase || !room) return;
    setStartError(null);
    setStarting(true);
    try {
      // Only the host can change the room (RLS). Only a lobby can be started.
      const { data, error } = await supabase
        .from("game_rooms")
        .update({ status: "playing" })
        .eq("id", room.id)
        .eq("status", "lobby")
        .select("status")
        .maybeSingle();
      if (error) throw error;
      if (!data) return setStartError("لم تبدأ اللعبة. ربما بدأت بالفعل، حدّث الصفحة.");
      setRoom((current) => (current ? { ...current, status: "playing" } : current));
    } catch {
      setStartError("تعذّر بدء اللعبة، حاول مرة أخرى.");
    } finally {
      setStarting(false);
    }
  }

  async function createRoom(event: FormEvent) {
    event.preventDefault();
    setFormError(null);
    const name = hostName.trim().replace(/\s+/g, " ");
    if (!selected) return setFormError("اختر لعبة أولاً.");
    if (name.length < 2 || name.length > 24) return setFormError("الاسم بين حرفين و24 حرفًا.");
    if (!supabase) return setFormError("الاتصال بقاعدة البيانات غير مضبوط بعد.");

    setBusy(true);
    try {
      const session = await ensureSession();
      const userId = session.user.id;

      // 1) Create the room. Its code is generated by the database trigger.
      const { data: created, error: roomError } = await supabase
        .from("game_rooms")
        .insert({ game_id: selected, settings: {} })
        .select("id, room_code, game_id, status")
        .single();
      if (roomError || !created) throw roomError ?? new Error("ROOM_CREATE_FAILED");
      const newRoom = created as RoomRow;

      // 2) Add the visitor as the host player.
      const { error: playerError } = await insertPlayer({ room_id: newRoom.id, user_id: userId, player_name: name, is_host: true }, "id");
      if (playerError) {
        // Don't leave an empty room behind (for example when the name is not allowed).
        await supabase.from("game_rooms").delete().eq("id", newRoom.id);
        throw playerError;
      }

      setRoom(newRoom);
      rememberRoom(newRoom.room_code, true);
    } catch (err) {
      setFormError(friendlyError(err));
    } finally {
      setBusy(false);
    }
  }

  if (room) {
    const game = games?.find((g) => g.id === room.game_id);
    const min = game?.min_players ?? 2;
    const max = game?.max_players ?? 12;
    const enough = players.length >= min;
    return (
      <Shell wide>
        <div className="mx-auto grid max-w-5xl gap-5 lg:grid-cols-[minmax(0,1fr)_420px] lg:items-start lg:gap-8 tv:max-w-none tv:grid-cols-[minmax(0,1fr)_600px]">
          {/* The room code and QR: what everyone in the room needs to see, large on a TV. */}
          <section aria-label="رمز الغرفة" className="surface relative grid justify-items-center gap-3 overflow-hidden rounded-[28px] p-6 text-center lg:order-2 lg:p-8">
            <span aria-hidden="true" className="pointer-events-none absolute inset-x-0 -top-24 mx-auto size-64 rounded-full bg-gold/15 blur-3xl" />
            <p className="text-[15px] font-semibold text-mist tv:text-xl">رمز الغرفة</p>
            <p className="room-code rounded-[18px] border border-gold/40 bg-night/60 px-5 py-2 text-[40px] leading-[52px] text-gold shadow-glow-gold lg:text-[48px] lg:leading-[60px] tv:text-[72px] tv:leading-[88px]">
              {room.room_code}
            </p>
            <p className="text-[15px] leading-[26px] text-mist tv:text-xl">شارك الرمز مع اللاعبين ليدخلوا من جوالاتهم.</p>

            <div className="mt-2 flex flex-col items-center gap-3">
              <QrCode text={joinLink(room.room_code)} className="size-44 lg:size-52 tv:size-72" />
              <p className="text-[13px] text-mist tv:text-lg">امسح الـ QR من الجوال، أو افتح الرابط:</p>
              <a href={joinLink(room.room_code)} className="break-all text-[15px] font-bold text-gold underline-offset-4 hover:underline tv:text-xl">
                {joinLink(room.room_code)}
              </a>
            </div>
            <Link
              to="/tv/$code"
              params={{ code: room.room_code }}
              target="_blank"
              className={cx(buttonBase, buttonTone("outline"), "mt-1")}
            >
              <Glyph name="tv" />
              افتح شاشة التلفزيون
            </Link>
            <p className="max-w-xs text-[13px] leading-6 text-mist tv:hidden">
              ما عندكم تلفزيون؟ تكفي الجوالات: كل لاعب يرى ما يحتاجه في جواله، والمضيف يقدر يعرض الشاشة من جواله بزر «اعرض هنا».
            </p>
          </section>

          <section className="grid gap-5 lg:order-1">
            {game ? (
              <div className="flex items-center gap-3">
                <GameIcon id={game.slug} />
                <h1 className="text-[26px] leading-9 lg:text-[34px] lg:leading-[46px] tv:text-[48px] tv:leading-[64px]">{game.title_ar}</h1>
              </div>
            ) : null}

            {room.status === "playing" ? (
              <div className="grid gap-3">
                <p className="flex items-center gap-2 rounded-[18px] border border-correct/50 bg-correct-fill/15 p-4 text-[16px] font-bold text-ivory">
                  <Glyph name="check" className="size-5 text-correct" />
                  بدأت اللعبة. تابع الشاشة الكبيرة.
                </p>
                <Link to="/host/$code" params={{ code: room.room_code }} className={cx(buttonBase, buttonTone("primary"), "min-h-14 w-full text-[17px]")}>
                  <Glyph name="tv" />
                  افتح شاشة المضيف
                </Link>
              </div>
            ) : (
              <div className="surface grid gap-3 rounded-[24px] p-5">
                <p className={cx("flex items-center gap-2 text-[16px] tv:text-xl", enough ? "text-ivory" : "text-mist")}>
                  <Glyph name={enough ? "check" : "hourglass"} className={cx("size-5", enough ? "text-correct" : "text-gold")} />
                  {enough ? "جاهزون للبدء." : `تحتاج ${min} لاعبين على الأقل للبدء.`} الحد الأقصى {max}.
                </p>
                {startError ? (
                  <p className="flex items-center gap-1.5 text-[14px] font-semibold text-wrong">
                    <Glyph name="alert" className="size-4" />
                    {startError}
                  </p>
                ) : null}
                <Button type="button" tone="primary" className="min-h-14 w-full text-[18px]" disabled={!enough || starting} onClick={startGame}>
                  {starting ? "جارٍ البدء…" : "ابدأ اللعبة"}
                </Button>
              </div>
            )}

            <div className="surface rounded-[24px] p-5">
              <h2 className="mb-3 flex items-center gap-2 text-[20px] tv:text-[30px]">
                <Glyph name="users" className="size-6 text-gold" />
                اللاعبون ({players.length})
              </h2>
              {playersError ? (
                <p role="alert" className="mb-3 flex items-start gap-2 rounded-[14px] border border-wrong/50 bg-wrong-fill/15 p-3 text-[14px] text-ivory">
                  <Glyph name="alert" className="mt-0.5 size-4 text-wrong" />
                  {playersError}
                </p>
              ) : null}
              <ul className="grid gap-2 sm:grid-cols-2">
                {players.map((p, i) => (
                  <li key={p.id} className="rise flex min-h-14 items-center gap-3 rounded-[14px] border border-line bg-deep-2/50 px-3 py-2 tv:min-h-20">
                    <Egg name={p.player_name} index={i + 1} avatar={p.avatar} size="sm" className="tv:w-11 tv:text-lg" />
                    <span className="min-w-0 flex-1 truncate text-[16px] font-semibold text-ivory tv:text-2xl">{p.player_name}</span>
                    {p.is_host ? <span className="rounded-full bg-violet/25 px-2.5 py-0.5 text-[13px] font-semibold text-violet-text tv:text-base">المضيف</span> : null}
                  </li>
                ))}
              </ul>
            </div>

            <Link to="/" className={cx(buttonBase, buttonTone("quiet"), "w-fit")}>
              <Glyph name="home" className="size-[18px]" />
              العودة للرئيسية
            </Link>
          </section>
        </div>
      </Shell>
    );
  }

  // Opened from a game («ابدأ الغرفة»): only that game, its details, and the host's name.
  const chosen = preselected && games ? games.find((g) => g.slug === preselected) ?? null : null;
  if ((preselected && games === null && !loadError) || resuming) {
    return (
      <Shell>
        <p className="mt-6 flex items-center gap-3 text-[15px] text-mist">
          <span aria-hidden="true" className="size-5 animate-spin rounded-full border-2 border-gold border-t-transparent motion-reduce:animate-none" />
          جارٍ التحميل…
        </p>
      </Shell>
    );
  }
  if (chosen) {
    const card = findCard(chosen.slug);
    const title = card?.title ?? chosen.title_ar;
    const dark = gameStyle(chosen.slug).ink === "dark";
    const ink = dark ? "text-on-gold" : "text-ivory";
    const soft = dark ? "text-on-gold/85" : "text-ivory/85";
    const chip = cx("inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-[14px] font-semibold", dark ? "bg-white/30" : "bg-black/25", ink);
    return (
      <Shell>
        <section className="mx-auto grid max-w-2xl gap-4">
          <header style={gameVars(chosen.slug)} className="gcard relative grid gap-3 overflow-hidden rounded-[28px] p-5 sm:p-7">
            <span aria-hidden="true" className="pointer-events-none absolute -top-16 -end-16 size-56 rounded-full bg-white/10 blur-3xl" />
            <div className="flex items-center gap-4">
              <span className="gcard-icon grid size-20 shrink-0 place-items-center rounded-full">
                <img src={`/brand/games/game-${chosen.slug}.svg`} alt="" className="size-16" />
              </span>
              <div className="grid min-w-0 gap-2">
                <h1 className={cx("text-[30px] leading-10 sm:text-[36px] sm:leading-[48px]", ink)}>{title}</h1>
                <div className="flex flex-wrap gap-2">
                  <span className={chip}>
                    <Glyph name="users" className="size-4" />
                    <bdi dir="ltr">{chosen.min_players}-{chosen.max_players}</bdi> لاعب
                  </span>
                  {card?.howTo ? (
                    <span className={chip}>
                      <Glyph name="clock" className="size-4" />
                      {card.howTo.minutes}
                    </span>
                  ) : null}
                </div>
              </div>
            </div>
            <p className={cx("text-[16px] leading-[29px]", soft)}>{card?.blurb ?? chosen.description_ar}</p>
          </header>

          <form onSubmit={createRoom} className="surface grid gap-4 rounded-[24px] p-5 sm:p-6">
            <Field label="اسمك (المضيف)">
              <input
                className={inputClass}
                value={hostName}
                onChange={(e) => setHostName(e.target.value)}
                maxLength={24}
                placeholder="اكتب اسمك"
                autoComplete="nickname"
              />
            </Field>
            {formError ? (
              <p className="flex items-center gap-1.5 text-[14px] font-semibold text-wrong">
                <Glyph name="alert" className="size-4" />
                {formError}
              </p>
            ) : null}
            <Button type="submit" tone="primary" disabled={busy || !selected} className="min-h-14 w-full text-[18px]">
              <Glyph name="users" />
              {busy ? "جارٍ الإنشاء…" : `افتح غرفة ${title}`}
            </Button>
            <p className="text-[13px] leading-6 text-mist">بعد فتح الغرفة يظهر رمزها ورمز QR، فينضم اللاعبون من جوالاتهم، ثم تبدأ اللعبة.</p>
          </form>

          {card?.howTo ? (
            <details className="surface group rounded-[24px] p-5 sm:p-6">
              <summary className="flex cursor-pointer list-none items-center gap-2 text-[19px] font-bold text-ivory">
                <Glyph name="question" className="size-6 text-gold" />
                طريقة اللعب
                <Glyph name="forward" className="ms-auto size-5 text-mist transition group-open:-rotate-90" />
              </summary>
              <p className="mt-3 text-[15px] leading-[27px] text-ivory">{card.howTo.goal}</p>
              <ol className="mt-3 grid gap-3">
                {card.howTo.steps.map((step, index) => (
                  <li key={step} className="flex gap-3 text-[15px] leading-[27px] text-mist">
                    <span className="btn-gold grid size-7 shrink-0 place-items-center rounded-full text-[13px] font-bold">{index + 1}</span>
                    <span>{step}</span>
                  </li>
                ))}
              </ol>
            </details>
          ) : null}

          <Link to="/play" search={{ game: "" }} className={cx(buttonBase, buttonTone("quiet"), "w-fit")}>
            <Glyph name="gamepad" className="size-[18px]" />
            اختر لعبة أخرى
          </Link>
        </section>
      </Shell>
    );
  }

  return (
    <Shell>
      <section className="mx-auto max-w-4xl">
        <div className="flex items-center gap-4">
          <Mark height={72} className="hidden sm:block" />
          <div>
            <h1 className="text-[30px] leading-10 lg:text-[40px] lg:leading-[52px]">إنشاء غرفة</h1>
            <p className="mt-1 text-[15px] leading-[26px] text-mist">اختر اللعبة، واكتب اسمك، ثم افتح الغرفة.</p>
            {preselected && games && !chosen ? <p className="mt-2 text-[14px] font-semibold text-gold">هذه اللعبة غير متاحة الآن، اختر لعبة أخرى.</p> : null}
          </div>
        </div>

        {loadError ? (
          <p className="mt-6 flex items-center gap-2 rounded-[18px] border border-wrong/50 bg-wrong-fill/15 p-4 text-[15px] text-ivory">
            <Glyph name="alert" className="size-5 text-wrong" />
            {loadError}
          </p>
        ) : games === null ? (
          <p className="mt-6 flex items-center gap-3 text-[15px] text-mist">
            <span aria-hidden="true" className="size-5 animate-spin rounded-full border-2 border-gold border-t-transparent motion-reduce:animate-none" />
            جارٍ تحميل الألعاب…
          </p>
        ) : (
          <form onSubmit={createRoom} className="mt-6 grid gap-6">
            <div className="grid gap-3 sm:grid-cols-2">
              {games.map((g) => {
                const on = selected === g.id;
                return (
                  <button
                    key={g.id}
                    type="button"
                    onClick={() => setSelected(g.id)}
                    aria-pressed={on}
                    className={cx(
                      "surface relative flex items-start gap-3 rounded-[22px] p-4 text-start transition",
                      on ? "border-gold! shadow-[0_0_0_3px_#ffa53a33,0_0_30px_-8px_#ffa53a88]!" : "hover:border-glow!",
                    )}
                  >
                    <GameIcon id={g.slug} />
                    <span className="grid min-w-0 flex-1 gap-1">
                      <span className="font-display text-[19px] font-bold leading-7 text-ivory">{g.title_ar}</span>
                      <span className="text-[14px] leading-6 text-mist">{g.description_ar}</span>
                      <span className="mt-1 inline-flex items-center gap-1.5 text-[13px] font-bold text-mist">
                        <Glyph name="users" className="size-[15px]" />
                        <bdi dir="ltr">{g.min_players}-{g.max_players}</bdi> لاعب
                      </span>
                    </span>
                    <span
                      aria-hidden="true"
                      className={cx("grid size-7 shrink-0 place-items-center rounded-full border-2", on ? "border-gold bg-gold text-on-gold" : "border-line-strong")}
                    >
                      {on ? <Glyph name="check" className="size-4" /> : null}
                    </span>
                  </button>
                );
              })}
            </div>

            <div className="surface grid gap-5 rounded-[24px] p-5 sm:p-6">
              <Field label="اسمك (المضيف)">
                <input
                  className={inputClass}
                  value={hostName}
                  onChange={(e) => setHostName(e.target.value)}
                  maxLength={24}
                  placeholder="اكتب اسمك"
                  autoComplete="nickname"
                />
              </Field>

              {formError ? (
                <p className="flex items-center gap-1.5 text-[14px] font-semibold text-wrong">
                  <Glyph name="alert" className="size-4" />
                  {formError}
                </p>
              ) : null}

              <Button type="submit" tone="primary" disabled={busy || !selected} className="min-h-14 w-full text-[18px]">
                {busy ? "جارٍ الإنشاء…" : "افتح الغرفة"}
              </Button>
            </div>
          </form>
        )}
      </section>
    </Shell>
  );
}

function friendlyError(err: unknown): string {
  const message = err instanceof Error ? err.message : String((err as { message?: string })?.message ?? err);
  if (message.includes("SUPABASE_NOT_CONFIGURED")) return "الاتصال بقاعدة البيانات غير مضبوط بعد.";
  if (message.includes("ANON_SIGNIN_FAILED") || message.toLowerCase().includes("anonymous"))
    return "تعذّر تسجيل الدخول المؤقت. تأكد من تفعيل Anonymous Sign-Ins في Supabase.";
  if (message.includes("ROOM_FULL")) return "الغرفة ممتلئة.";
  if (message.includes("NAME_NOT_ALLOWED")) return "هذا الاسم غير مسموح. اختر اسمًا آخر.";
  if (message.includes("ROOM_FINISHED")) return "انتهت هذه الغرفة.";
  return "تعذّر إنشاء الغرفة، حاول مرة أخرى.";
}
