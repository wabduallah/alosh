-- يغيّر نص دليل إذا كان كما كتبناه أول مرة.
create or replace function pg_temp.court_soften(p_slug text, p_title text, p_old text, p_new text)
returns void
language sql
as $$
  update public.court_cases c
     set evidence = (select jsonb_agg(case when e->>'title' = p_title and e->>'text' = p_old then e || jsonb_build_object('text', p_new) else e end order by o)
                       from jsonb_array_elements(c.evidence) with ordinality t(e, o))
   where c.slug = p_slug;
$$;

-- يضيف أدلة لأدوار ليس عندها أدلة: {"<مفتاح الدور>": [{title, text, icon, time}]}
create or replace function pg_temp.court_exhibits(p_slug text, p_map jsonb)
returns void
language sql
as $$
  update public.court_cases c
     set roles = (select jsonb_agg(case when p_map ? (r->>'key') and not (r ? 'exhibits') then r || jsonb_build_object('exhibits', p_map->(r->>'key')) else r end order by o)
                    from jsonb_array_elements(c.roles) with ordinality t(r, o))
   where c.slug = p_slug;
$$;

create or replace function pg_temp.court_variants(p_slug text, p_variants jsonb)
returns void
language sql
as $$
  update public.court_cases set variants = p_variants where slug = p_slug and variants is null;
$$;

