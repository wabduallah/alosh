-- 2) «غش في دوري البلوت» بمتهمَين: صالح وشريكه بندر ---------------------------------
do $$
declare
  v_roles jsonb;
begin
  select roles into v_roles from public.court_cases where slug = 'baloot-cheat';
  if v_roles is null or exists (select 1 from jsonb_array_elements(v_roles) r where r->>'key' = 'accused-2') then
    return;
  end if;
  v_roles := (select jsonb_agg(
      case
        when r->>'key' = 'accused' then r || '{"guilty":true}'::jsonb
        when r->>'key' = 'lawyer' and r->>'secret' like 'موكلك عنده حساسية%' then r || jsonb_build_object('brief', 'يدافع عن صالح وبندر.',
          'secret', 'تدافع عن الاثنين. صالح عنده حساسية والغبار كان كثيرًا تلك الليلة، وبندر لاعب ماهر يحفظ الأوراق. ركّز على أن الحظ في البلوت وارد، وأن أحدًا لم يرَ إشارة مفهومة. وإن ضاق الخناق، تقدر تنقذ واحدًا على الأقل.')
        when r->>'key' = 'prosecutor' and r->>'secret' like 'ملفك: شريك صالح%' then r || jsonb_build_object(
          'secret', 'ملفك: بندر، شريك صالح، أعلن الحكم الصحيح في كل جولة حاسمة. اسأل صالح: متى بدأت الحساسية؟ واسأل بندر: لماذا لم تنجح «مهارتك» في نصف النهائي؟ تطلب إدانة الاثنين.')
        else r
      end order by o)
    from jsonb_array_elements(v_roles) with ordinality t(r, o));
  v_roles := v_roles || '[{"key":"accused-2","kind":"accused","guilty":true,"name":"بندر، شريك صالح","brief":"أعلن الأحكام في النهائي.",
    "secret":"أنت مذنب مع صالح: اتفقتما على الإشارات قبل الدوري، اليمنى للهاص واليسرى للشريا. قصتك: أنت تقرأ اللعب وتحفظ الأوراق، ولم تنتبه لأذن صالح أصلًا.",
    "goal":"لا تذكر كلمة «إشارة» أبدًا، حتى لو سُئلت عنها مباشرة."}]'::jsonb;
  update public.court_cases
     set roles = v_roles,
         intro = case when intro like 'في نهائي دوري البلوت في الاستراحة%' then
           'في نهائي دوري البلوت في الاستراحة، فاز صالح وشريكه بندر بشكل مدهش: كل «حكم» أعلنه بندر كان في محله. الفريق الخاسر اتهم الاثنين بالغش: صالح يرسل إشارات بلمس أذنه، وبندر يقرؤها. ويطالبون بسحب اللقب والجائزة.' else intro end,
         truth = case when truth like 'صالح مذنب. اتفق مع شريكه%' then
           'صالح وبندر مذنبان. اتفقا قبل الدوري على إشارات: لمس الأذن اليمنى للحكم في الهاص، واليسرى للشريا. المقطع يُظهر اللمسة قبل كل حكم في الجولات الحاسمة، وبندر جلس مقابل صالح في النهائي ليرى أذنه. حكاية «حساسية الأذن» لم تظهر إلا في النهائي، ولم يلمس صالح أذنه مرة واحدة في نصف النهائي.' else truth end,
         summary = case when coalesce(summary, '') = '' then 'متهمان بالغش في نهائي البلوت.' else summary end
   where slug = 'baloot-cheat';
end $$;

