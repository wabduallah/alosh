export function gameSeo(card: GameCard) {
  const s = SEO[card.id];
  const [min, max] = card.players.split("-").map((n) => Number(n));
  const faq = [{ q: `كم عدد لاعبي ${card.title}؟`, a: `من ${min} إلى ${max ?? min} لاعبين، ولكل لاعب جواله.` }, ...(s?.faq ?? []), ...COMMON];
  return { keywords: s?.keywords ?? "", examples: s?.examples ?? null, faq };
}

/** schema.org data for a game page: the game and its common questions. */
export function gameJsonLd(card: GameCard, url: string) {
  const { faq } = gameSeo(card);
  const [min, max] = card.players.split("-").map((n) => Number(n));
  return [
    {
      "@context": "https://schema.org",
      "@type": "Game",
      name: card.title,
      description: card.blurb,
      url,
      inLanguage: "ar",
      numberOfPlayers: { "@type": "QuantitativeValue", minValue: min, maxValue: max ?? min },
      isAccessibleForFree: true,
      publisher: { "@type": "Organization", name: "العش", url: "https://www.al3sh.app" },
    },
    {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      mainEntity: faq.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
    },
  ];
}
