-- يضيف أدلة لقضية: ما لم يكن عنوانه موجودًا، وحتى 15 دليلًا.
create or replace function pg_temp.court_add_evidence(p_slug text, p_items jsonb)
returns void
language plpgsql
as $$
declare
  v_item jsonb;
  v_ev jsonb;
begin
  select evidence into v_ev from public.court_cases where slug = p_slug;
  if v_ev is null then
    return;
  end if;
  for v_item in select * from jsonb_array_elements(p_items) loop
    if jsonb_array_length(v_ev) < 15 and not exists (select 1 from jsonb_array_elements(v_ev) e where e->>'title' = v_item->>'title') then
      v_ev := v_ev || jsonb_build_array(v_item);
    end if;
  end loop;
  update public.court_cases set evidence = v_ev where slug = p_slug and evidence is distinct from v_ev;
end;
$$;

