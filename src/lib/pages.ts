export type PageBlock =
  | { kind: "h"; text: string }
  | { kind: "p"; text: string }
  | { kind: "ul"; items: string[] }
  | { kind: "qa"; q: string; a: PageBlock[] };

/** Plain text → blocks. Never HTML, so nothing the admin types can run as code. */
export function parsePage(text: string): PageBlock[] {
  const out: PageBlock[] = [];
  let target = out;
  let para: string[] = [];
  let list: string[] | null = null;
  const flush = () => {
    if (para.length) target.push({ kind: "p", text: para.join(" ") });
    if (list) target.push({ kind: "ul", items: list });
    para = [];
    list = null;
  };
  for (const raw of text.replace(/\r/g, "").split("\n")) {
    const line = raw.trim();
    if (!line) {
      flush();
      continue;
    }
    if (line.startsWith("## ")) {
      flush();
      target = out;
      out.push({ kind: "h", text: line.slice(3).trim() });
    } else if (line.startsWith("؟ ") || line.startsWith("? ")) {
      flush();
      const qa: PageBlock = { kind: "qa", q: line.slice(2).trim(), a: [] };
      out.push(qa);
      target = qa.a;
    } else if (line.startsWith("- ")) {
      if (para.length) {
        target.push({ kind: "p", text: para.join(" ") });
        para = [];
      }
      (list ??= []).push(line.slice(2).trim());
    } else {
      if (list) {
        target.push({ kind: "ul", items: list });
        list = null;
      }
      para.push(line);
    }
  }
  flush();
  return out;
}
