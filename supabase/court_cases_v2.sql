-- 1) القضايا الست الأولى -------------------------------------------------------

create or replace function pg_temp.court_patch(p_slug text, p_times jsonb, p_fallbacks jsonb)
returns void
language plpgsql
as $$
begin
  update public.court_cases c
     set evidence = (select jsonb_agg(case when p_times ? (e->>'title') then e || jsonb_build_object('time', p_times->>(e->>'title')) else e end order by o)
                       from jsonb_array_elements(c.evidence) with ordinality t(e, o)),
         roles = (select jsonb_agg(case when p_fallbacks ? (r->>'key') then r || (p_fallbacks->(r->>'key')) else r end order by o)
                    from jsonb_array_elements(c.roles) with ordinality t(r, o))
   where c.slug = p_slug and c.updated_at = c.created_at;
end;
$$;

